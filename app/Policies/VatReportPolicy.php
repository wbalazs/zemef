<?php

namespace App\Policies;

use App\User;
use App\Models\VatReport;
use Illuminate\Auth\Access\HandlesAuthorization;

class VatReportPolicy
{
    use HandlesAuthorization;

    /**
     * Determine whether the user can see the items.
     *
     * @param  \App\User  $user
     * @return boolean
     */
    public function viewAny(User $user)
    {
        return true;
    }

    /**
     * Determine whether the user can create items.
     *
     * @param  \App\User  $user
     * @return boolean
     */
    public function create(User $user)
    {
        return $user->hasPermission('create', VatReport::class);
    }

    /**
     * Determine whether the user can update the item.
     *
     * @param  \App\User  $user
     * @param  \App\Item  $item
     * @return boolean
     */
    public function update(User $user, VatReport $vatReport)
    {
        return $user->hasPermission('edit', VatReport::class);
    }

    /**
     * Determine whether the user can delete the item.
     *
     * @param  \App\User  $user
     * @param  \App\Item  $item
     * @return boolean
     */
    public function delete(User $user, VatReport $vatReport)
    {
        return $user->hasPermission('delete', VatReport::class);
    }
}
