<?php

namespace App\Policies;

use App\User;
use App\Models\InventoryControl;
use Illuminate\Auth\Access\HandlesAuthorization;

class InventoryControlPolicy
{
    use HandlesAuthorization;

    /**
     * Determine whether the user can see the items.
     *
     * @param  \App\User  $user
     * @return boolean
     */
    public function viewAny(User $user)
    {
        return $user->hasPermission('index', InventoryControl::class);
    }

    /**
     * Determine whether the user can create items.
     *
     * @param  \App\User  $user
     * @return boolean
     */
    public function create(User $user)
    {
        return $user->hasPermission('create', InventoryControl::class);
    }

    /**
     * Determine whether the user can update the item.
     *
     * @param  \App\User  $user
     * @param  \App\Item  $item
     * @return boolean
     */
    public function update(User $user, InventoryControl $inventorycontrol)
    {
        return $user->hasPermission('edit', InventoryControl::class);
    }

    /**
     * Determine whether the user can delete the item.
     *
     * @param  \App\User  $user
     * @param  \App\Item  $item
     * @return boolean
     */
    public function delete(User $user, InventoryControl $inventorycontrol)
    {
        return $user->hasPermission('delete', InventoryControl::class);
    }
}
